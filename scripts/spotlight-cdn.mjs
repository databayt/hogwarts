#!/usr/bin/env node
// Refresh the "On the CDN" block under each SPOTLIGHT.md's "Real screens to show".
//
// A spotlight names its shoot/record flows in frontmatter (`flows: [mark-attendance]`);
// those flows publish to cdn.databayt.org/hogwarts/<lang>/<route>/… and record every
// asset in src/components/docs/media-manifest.json. This writes the Arabic screens
// (and tutorial) of those flows between the <!-- cdn:start --> / <!-- cdn:end -->
// markers, so the content and media teams get links they can open instead of
// repo-local docs/evidence paths. Re-run after a re-shoot; then re-run
// `node scripts/social-concepts.mjs` in kun so the social block picks them up.
//
//   node scripts/spotlight-cdn.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dirname, "..")
const components = join(root, "src", "components")
const manifest = JSON.parse(readFileSync(join(components, "docs", "media-manifest.json"), "utf8"))
const entries = manifest.entries ?? manifest
const check = process.argv.includes("--check")

const narrowest = (o) => (o ? o[Object.keys(o).map(Number).sort((a, b) => a - b)[0]] : undefined)
const bare = (u) => u?.replace(/\?v=.*$/, "")

function spotlights(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) spotlights(p, out)
    else if (e.name === "SPOTLIGHT.md") out.push(p)
  }
  return out.sort()
}

let stale = 0
for (const file of spotlights(components)) {
  const text = readFileSync(file, "utf8")
  const flows = /^flows:\s*\[(.*)\]\s*$/m.exec(text)?.[1].split(",").map((s) => s.trim()).filter(Boolean)
  if (!flows?.length) continue
  const lines = []
  for (const flow of flows) {
    for (const [id, e] of Object.entries(entries)) {
      if (!id.startsWith(`${flow}/`) || !id.endsWith("-ar")) continue
      if (e.kind === "video") {
        const src = e.sources?.find((s) => /avc1/.test(s.type))?.src ?? e.sources?.[0]?.src
        lines.push(`- Video — ${e.title?.en ?? id}: ${bare(src)}`)
      } else {
        lines.push(`- ${e.alt?.en ?? id}: ${bare(narrowest(e.webp) ?? narrowest(e.avif))}`)
      }
    }
  }
  const block = [
    "<!-- cdn:start — generated by scripts/spotlight-cdn.mjs from flows:; re-run after a re-shoot -->",
    "On the CDN, ready to attach (Arabic; swap `/ar/` for `/en/` in a link for the English screen):",
    "",
    ...(lines.length ? lines : [`- (nothing published yet for ${flows.join(", ")} — shoot the routes above)`]),
    "<!-- cdn:end -->",
  ].join("\n")
  const next = /<!-- cdn:start[\s\S]*?<!-- cdn:end -->/.test(text)
    ? text.replace(/<!-- cdn:start[\s\S]*?<!-- cdn:end -->/, block)
    : text.replace(/^## Real screens to show\n\n/m, `## Real screens to show\n\n${block}\n\n`)
  if (next === text) continue
  stale++
  if (!check) writeFileSync(file, next)
  console.log(`${check ? "stale" : "updated"} ${file.slice(root.length + 1)} (${lines.length})`)
}
if (check && stale) process.exit(1)
console.log(stale ? `${stale} spotlight(s) ${check ? "stale" : "updated"}` : "✓ spotlight CDN blocks up to date")
