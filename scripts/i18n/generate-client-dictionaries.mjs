/**
 * Regenerates src/components/internationalization/client/{ar,en}.ts — the
 * static client dictionaries LocaleDictionaryProvider serves — from the
 * namespace registry in namespaces.ts, with the same merge as the server
 * `getDictionary`: the four flat files spread in order, then every feature
 * namespace nested under its key.
 *
 *   node scripts/i18n/generate-client-dictionaries.mjs
 *
 * Run it after adding or renaming a namespace in namespaces.ts;
 * src/tests/i18n/client-dictionary.test.ts fails until you do.
 */
import fs from "node:fs"
import path from "node:path"

const dir = path.resolve("src/components/internationalization")
const registry = fs.readFileSync(path.join(dir, "namespaces.ts"), "utf8")

const start = registry.indexOf("export const featureDictionaries")
const block = registry.slice(start, registry.indexOf("} as const", start))
const features = [
  ...block.matchAll(
    /\n {2}(\w+): \{\n\s+en: \(\) =>\s*\n?\s*import\("\.\/dictionaries\/en\/([\w-]+)\.json"\)/g
  ),
].map((m) => ({ key: m[1], file: m[2] }))
if (features.length === 0) throw new Error("no feature namespaces found")

for (const loc of ["ar", "en"]) {
  const flat = {
    general: `${loc}.json`,
    school: `school-${loc}.json`,
    lumos: `lumos-${loc}.json`,
    operator: `operator-${loc}.json`,
  }
  const language = loc === "ar" ? "Arabic" : "English"
  const lines = [
    "// Copyright (c) 2025-present databayt",
    "// Licensed under SSPL-1.0 -- see LICENSE for details",
    "",
    `// GENERATED by scripts/i18n/generate-client-dictionaries.mjs from ../namespaces.ts`,
    `// — the whole ${language} dictionary as one static module. Same merge as the`,
    "// server `getDictionary`: the four flat files spread in order, then every",
    "// feature namespace nested under its key. Do not edit; regenerate.",
    "",
    'import type { Dictionary } from "../dictionaries"',
    ...Object.entries(flat).map(([k, f]) => `import ${k} from "../${f}"`),
    ...features.map(
      ({ key, file }) =>
        `import ${key} from "../dictionaries/${loc}/${file}.json"`
    ),
    "",
    "export const dictionary = {",
    ...Object.keys(flat).map((k) => `  ...${k},`),
    ...features.map(({ key }) => `  ${key},`),
    "} as unknown as Dictionary",
    "",
  ]
  fs.writeFileSync(path.join(dir, "client", `${loc}.ts`), lines.join("\n"))
}
console.log(
  `wrote client/ar.ts and client/en.ts (${features.length} feature namespaces)`
)
