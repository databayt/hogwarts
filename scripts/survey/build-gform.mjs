/**
 * Emits scripts/survey/google-form.gs — a Google Apps Script that builds the
 * Google Form twin of the in-app survey (/survey) from the SAME source:
 * the question list in src/components/saas-marketing/survey/config.ts and the
 * Arabic words in dictionaries/ar/survey.json.
 *
 *   node scripts/survey/build-gform.mjs [ar|en]
 *
 * Then paste google-form.gs into script.google.com (signed in as the databayt
 * Google account) → Run `createSurveyForm` → the log prints the edit + share URLs.
 * The Google Form stores its own answers — it does not sync with the app.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const lang = process.argv[2] === "en" ? "en" : "ar"

// config.ts is plain data + a few helpers; strip types and evaluate the
// QUESTIONS / SECTIONS literals rather than pulling in a TS toolchain.
const src = readFileSync(
  join(root, "src/components/saas-marketing/survey/config.ts"),
  "utf8"
)
const literal = (name) => {
  const start = src.indexOf(`export const ${name}`)
  const eq = src.indexOf("= [", start)
  let depth = 0
  for (let i = eq + 2; i < src.length; i++) {
    if (src[i] === "[") depth++
    else if (src[i] === "]" && --depth === 0) {
      return Function(`return ${src.slice(eq + 2, i + 1)}`)()
    }
  }
  throw new Error(`${name} not found in config.ts`)
}
const QUESTIONS = literal("QUESTIONS")
const t = JSON.parse(
  readFileSync(
    join(root, `src/components/internationalization/dictionaries/${lang}/survey.json`),
    "utf8"
  )
)

const s = (v) => JSON.stringify(v)
const lines = []
const out = (l = "") => lines.push(l)

out(`// GENERATED by scripts/survey/build-gform.mjs (${lang}) — do not edit by hand.`)
out(`// Run createSurveyForm() at script.google.com, signed in as the databayt account.`)
out(`function createSurveyForm() {`)
out(`  var form = FormApp.create(${s(t.meta.title)});`)
out(`  form.setDescription(${s(`${t.welcome.body}\n\n${t.welcome.duration} · ${t.welcome.privacy}`)});`)
out(`  form.setProgressBar(true);`)
out(`  form.setCollectEmail(false);`)
out(`  form.setConfirmationMessage(${s(`${t.thanks.title} — ${t.thanks.body}`)});`)
out()

let section = null
for (const q of QUESTIONS) {
  if (q.section !== section) {
    section = q.section
    if (q !== QUESTIONS[0]) {
      out(`  form.addPageBreakItem().setTitle(${s(t.sections[section])});`)
    } else {
      out(`  form.addSectionHeaderItem().setTitle(${s(t.sections[section])});`)
    }
  }
  const copy = t.questions[q.id]
  const v = `q_${q.id}`
  const required = !q.optional
  const choices = (q.options ?? []).filter((o) => o !== q.other)

  if (q.showIf) {
    // The conditional question gets its own page; the choice that reveals it
    // jumps there, every other choice submits the form.
    out(`  var page_${q.id} = form.addPageBreakItem().setTitle(${s(t.sections[q.section])});`)
  }

  switch (q.type) {
    case "single":
    case "multi": {
      const kind = q.type === "single" ? "addMultipleChoiceItem" : "addCheckboxItem"
      out(`  var ${v} = form.${kind}().setTitle(${s(copy.title)}).setRequired(${required});`)
      if (q.type === "multi") out(`  ${v}.setHelpText(${s(t.nav.multiHint)});`)
      out(`  ${v}.setChoiceValues(${s(choices.map((o) => copy.options[o]))});`)
      if (q.other) out(`  ${v}.showOtherOption(true);`)
      break
    }
    case "scale":
      out(`  form.addScaleItem().setTitle(${s(copy.title)}).setBounds(1, 5).setLabels(${s(copy.low)}, ${s(copy.high)}).setRequired(${required});`)
      break
    case "text":
      out(`  form.addParagraphTextItem().setTitle(${s(copy.title)}).setRequired(${required})${q.optional ? `.setHelpText(${s(t.nav.optional)})` : ""};`)
      break
    case "email":
      out(`  form.addTextItem().setTitle(${s(copy.title)}).setHelpText(${s(copy.hint)}).setRequired(true)`)
      out(`    .setValidation(FormApp.createTextValidation().requireTextIsEmail().build());`)
      break
  }
}

// Wire the branch: showIf.equals → the conditional page, anything else → submit.
for (const q of QUESTIONS.filter((x) => x.showIf)) {
  const parent = QUESTIONS.find((x) => x.id === q.showIf.id)
  const copy = t.questions[parent.id]
  out()
  out(`  q_${parent.id}.setChoices([`)
  for (const o of parent.options) {
    const nav = o === q.showIf.equals ? `page_${q.id}` : "FormApp.PageNavigationType.SUBMIT"
    out(`    q_${parent.id}.createChoice(${s(copy.options[o])}, ${nav}),`)
  }
  out(`  ]);`)
}

out()
out(`  Logger.log("Edit:  " + form.getEditUrl());`)
out(`  Logger.log("Share: " + form.shortenFormUrl(form.getPublishedUrl()));`)
out(`}`)

const file = join(root, "scripts/survey/google-form.gs")
writeFileSync(file, lines.join("\n") + "\n")
console.log(`wrote ${file} (${QUESTIONS.length} questions, ${lang})`)
